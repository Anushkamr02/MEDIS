import { supabase } from './supabaseClient';

// The MEDIS AI service (backend/server.py)
const AI_BASE_URL = (import.meta.env.VITE_API_URL || 'http://localhost:8000').replace(/\/$/, '');

const UNAVAILABLE =
  'AI service is unavailable. Start the backend (backend/server.py) and try again.';

async function authHeaders() {
  const { data } = await supabase.auth.getSession();
  const token = data.session?.access_token;
  return token ? { Authorization: `Bearer ${token}` } : {};
}

function errorMessage(payload, status) {
  const detail = payload?.detail;
  if (typeof detail === 'string') return detail;
  if (Array.isArray(detail)) return detail.map((d) => d.msg).join('; ');
  return `Request failed (${status})`;
}

/**
 * Calls the AI service with the user's Supabase token (the service reads
 * Supabase as this user, so RLS still applies). Pass `body` for JSON or
 * `formData` for file uploads. Returns { data, error } like supabase-js.
 */
export async function aiRequest(path, { method = 'POST', body, formData } = {}) {
  const headers = await authHeaders();
  if (body !== undefined) headers['Content-Type'] = 'application/json';

  let response;
  try {
    response = await fetch(`${AI_BASE_URL}${path}`, {
      method,
      headers,
      body: formData ?? (body !== undefined ? JSON.stringify(body) : undefined),
    });
  } catch {
    return { data: null, error: UNAVAILABLE };
  }

  const payload = await response.json().catch(() => null);
  if (!response.ok) return { data: null, error: errorMessage(payload, response.status) };
  return { data: payload, error: null };
}

/**
 * Opens a PDF generated by the AI service in a new tab. The tab is opened
 * synchronously so popup blockers allow it, then pointed at the file.
 */
export async function openAiPdf(path) {
  const tab = window.open('', '_blank');
  try {
    const response = await fetch(`${AI_BASE_URL}${path}`, { headers: await authHeaders() });
    if (!response.ok) {
      const payload = await response.json().catch(() => null);
      tab?.close();
      return { error: errorMessage(payload, response.status) };
    }
    const url = URL.createObjectURL(await response.blob());
    if (tab) tab.location.href = url;
    return { error: null };
  } catch {
    tab?.close();
    return { error: UNAVAILABLE };
  }
}
