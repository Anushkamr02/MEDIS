/**
 * Convenience wrapper: options as [value, label] pairs (or plain strings).
 * Radix Select can't hold an empty value, so '' shows the placeholder.
 */
export function SimpleSelect({ value, onChange, options, placeholder = 'Select', disabled, id, className, ariaLabel }) {
  return (
    <Select value={value || undefined} onValueChange={onChange} disabled={disabled}>
      <SelectTrigger id={id} className={className} aria-label={ariaLabel}>
        <SelectValue placeholder={placeholder} />
      </SelectTrigger>
      <SelectContent>
        {options.map((o) => {
          const [v, l] = Array.isArray(o) ? o : [o, o];
          return (
            <SelectItem key={v} value={v}>
              {l}
            </SelectItem>
          );
        })}
      </SelectContent>
    </Select>
  );
}

